create table if not exists users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  phone text,
  password_hash text not null,
  role text not null default 'patient' check (role in ('patient','admin')),
  created_at timestamptz not null default now()
);

create table if not exists specializations (
  id int generated by default as identity primary key,
  name text not null unique
);

create table if not exists doctors (
  id int generated by default as identity primary key,
  name text not null,
  specialization_id int not null references specializations(id),
  experience_years int default 0,
  fee numeric(8,2) default 0,
  bio text,
  created_at timestamptz not null default now()
);

-- Doctor ka weekly schedule. day_of_week: 0=Sunday ... 6=Saturday
create table if not exists doctor_availability (
  id int generated by default as identity primary key,
  doctor_id int not null references doctors(id) on delete cascade,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  start_time time not null,
  end_time time not null,
  slot_minutes int not null default 30,
  unique (doctor_id, day_of_week, start_time)
);

create table if not exists appointments (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id),
  doctor_id int not null references doctors(id),
  appointment_date date not null,
  start_time time not null,
  end_time time not null,
  reason text,
  status text not null default 'booked' check (status in ('booked','cancelled','completed')),
  created_at timestamptz not null default now()
);

-- Double booking rokne ka tarika: sirf 'booked' rows par unique.
-- Cancel hone ke baad wahi slot dobara book ho sakta hai.
create unique index if not exists uq_doctor_slot
  on appointments (doctor_id, appointment_date, start_time)
  where status = 'booked';

-- SECURITY: Supabase ki public API in tables ko na khol sake isliye RLS ON.
-- Hamara Express backend direct Postgres se judta hai, usko isse farak nahi padta.
alter table users enable row level security;
alter table specializations enable row level security;
alter table doctors enable row level security;
alter table doctor_availability enable row level security;
alter table appointments enable row level security;
